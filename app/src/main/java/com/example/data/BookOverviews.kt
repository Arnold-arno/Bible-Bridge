    fun getOverviewForBook(bookName: String): BookOverview {
        val normalized = bookName.lowercase().trim()
        val found = overviews.firstOrNull { 
            it.name.equals(bookName, ignoreCase = true) ||
            (normalized == "1 kings" || normalized == "2 kings") && it.name.contains("Kings") ||
            (normalized == "1 samuel" || normalized == "2 samuel") && it.name.contains("Samuel") ||
            (normalized == "1 corinthians" || normalized == "2 corinthians") && it.name.contains("Corinthians") ||
            (normalized == "1 thessalonians" || normalized == "2 thessalonians") && it.name.contains("Thessalonians") ||
            (normalized == "1 peter" || normalized == "2 peter") && it.name.contains("Peter") ||
            (normalized == "1 john" || normalized == "2 john" || normalized == "3 john") && it.name.contains("John")
        } ?: BookOverview(
            name = bookName,
            category = "Scripture",
            author = "Inspired Authors",
            dateWritten = "Various BC/AD",
            theme = "God's Redemption of Humanity",
            keyVerse = "2 Timothy 3:16 - 'All Scripture is breathed out by God...'",
            summary = "One of the inspired books of Holy Scripture, contributing to the complete narrative of God's love, covenant, and salvation plan for mankind."
        )
        
        val chars = if (found.characters.isNotEmpty()) found.characters else getCharactersForBook(bookName)
        val less = if (found.lessons.isNotEmpty()) found.lessons else getLessonsForBook(bookName)
        val scenes = if (found.majorScenes.isNotEmpty()) found.majorScenes else getMajorScenesForBook(bookName)
        
        // Dynamic summary based on length
        val dynamicSummary = getDynamicSummary(bookName, found.summary)
        
        val keyCharsList = getCharactersListForBook(bookName)
        val centralLessList = getLessonsListForBook(bookName)
        
        return found.copy(
            name = bookName,
            summary = dynamicSummary,
            characters = chars,
            lessons = less,
            majorScenes = scenes,
            keyCharacters = keyCharsList,
            centralLessons = centralLessList
        )
    }

