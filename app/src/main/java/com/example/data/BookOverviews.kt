    fun getDynamicSummary(bookName: String, originalSummary: String): String {
        val chCount = getBookChaptersCount(bookName)
        val lengthCategory = when {
            chCount <= 5 -> "Short (Concise Narrative / Focused Epistle)"
            chCount <= 15 -> "Medium (Theologically Concentrated Letter / Detailed Prophecy)"
            else -> "Long (Epic Historical Scroll / Major Prophet / Theological Cornerstone)"
        }
        
        val segmentCount = when {
            chCount <= 5 -> "1-2 short devotional readings"
            chCount <= 15 -> "4-5 structured study sections"
            else -> "8-10 major thematic acts"
        }

        val pacingGuide = when {
            chCount <= 5 -> "Designed for continuous, single-sitting reading (approx. 10-15 minutes). Focus heavily on the immediate context, personal relationships, and direct emotional or spiritual instructions."
            chCount <= 15 -> "Best consumed in 3-4 distinct study periods. Pay close attention to the logical progression of paragraphs, doctrinal arguments, and recurring key terms."
            else -> "A majestic, multi-part journey requiring a structured reading plan (e.g., 1-2 chapters daily). Map out the major historical transitions, geographical movements, and covenant updates across generations."
        }

        // Structural Breakdown
        val structureOutline = when (bookName.lowercase().trim()) {
            "genesis" -> "• Chapters 1-11: Primeval History (Creation, Fall, Flood, Babel)\n• Chapters 12-25: Abrahamic Covenant & Journeys\n• Chapters 26-36: Isaac and Jacob's Descendants\n• Chapters 37-50: The Providence of Joseph in Egypt"
